# Clave de Scene.pck
# =============================================================================

def find_key(raws: List[bytes], check=None) -> Optional[bytes]:
    """
    Recupera la clave de 16 bytes a partir de las escenas cifradas (raws, ya sin nada más).
    Bytes 0-3: tras quitar TABLE_A, cada escena empieza por su tamaño comprimido (= su longitud).
    Bytes 4-15: el texto UTF-16 deja muchos 0x00 literales, así que en cada posición mod 16 el
    byte más frecuente es la clave. check(key) valida la clave candidata (todas las escenas).
    """
    plain = [xor_repeat(r, TABLE_A) for r in raws if len(r) >= 16]
    if not plain:
        return None
    key = bytearray(16)
    for j in range(4):
        votes = Counter(d[j] ^ struct.pack('<I', len(d))[j] for d in plain)
        key[j] = votes.most_common(1)[0][0]
    counts = [Counter() for _ in range(16)]
    for d in plain:
        arr = np.frombuffer(d, np.uint8)
        for j in range(4, 16):
            counts[j].update(arr[j::16].tolist())
    for j in range(4, 16):
        key[j] = counts[j].most_common(1)[0][0]
    key = bytes(key)
    if check is not None and not check(key):
        return None
    return key


def candidate_keys() -> Iterable[bytes]:
    return KNOWN_KEYS.values()
