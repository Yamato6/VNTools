_native = None


def load_native():
    """Carga _siglus.dll una vez; None si no está disponible."""
    global _native
    if _native is None:
        _native = False
        dirs = [Path(__file__).resolve().parent]
        if hasattr(sys, '_MEIPASS'):
            dirs.insert(0, Path(sys._MEIPASS))
        for d in dirs:
            lib = d / LIB_NAME
            if not lib.exists():
                continue
            try:
                so = ctypes.CDLL(str(lib))
            except OSError:
                continue
            so.lz_unpack.argtypes = [ctypes.c_char_p, ctypes.c_int64, ctypes.c_void_p, ctypes.c_int64,
                                     ctypes.c_int, ctypes.c_int]
            so.lz_unpack.restype = ctypes.c_int64
            so.nwa_decode.argtypes = [ctypes.c_char_p, ctypes.c_int64, ctypes.c_void_p, ctypes.c_int,
                                      ctypes.c_int, ctypes.c_int, ctypes.c_int, ctypes.c_int, ctypes.c_int,
                                      ctypes.c_int, ctypes.c_void_p, ctypes.c_int64]
            so.nwa_decode.restype = ctypes.c_int64
            _native = so
            break
    return _native or None


def native_available() -> bool:
    return load_native() is not None


# =============================================================================
# XOR
# =============================================================================

def xor_repeat(data: bytes, key: bytes) -> bytes:
    """data XOR key repetida (key de 16 o 256 bytes)."""
    if not data:
        return data
    arr = np.frombuffer(data, np.uint8)
    k = np.frombuffer(key, np.uint8)
    reps = -(-len(arr) // len(k))
    return (arr ^ np.tile(k, reps)[:len(arr)]).tobytes()


# =============================================================================
# LZ
# =============================================================================

def lz_unpack_raw(src: bytes, size: int, min_count: int = 2, bpp: int = 1) -> bytes:
    """Descomprime el flujo LZ (sin la cabecera de 8 bytes) a size bytes."""
    so = load_native()
    if so:
        out = ctypes.create_string_buffer(size)
        n = so.lz_unpack(src, len(src), out, size, min_count, bpp)
        if n < 0:
            raise ValueError("damaged compressed data")
        return out.raw[:n] if n < size else out.raw
    out = bytearray(size)
    s = d = 0
    n_src = len(src)
    bits = 2
    while d < size and s < n_src:
        bits >>= 1
        if bits == 1:
            bits = src[s] | 0x100
            s += 1
        if bits & 1:
            chunk = src[s:s + bpp]
            out[d:d + len(chunk)] = chunk
            s += bpp
            d += bpp
        else:
            if s + 2 > n_src:
                break
            v = src[s] | (src[s + 1] << 8)
            s += 2
            count = ((v & 0xF) + min_count) * bpp
            off = (v >> 4) * bpp
            if off == 0 or off > d:
                raise ValueError("damaged compressed data")
            for k in range(min(count, size - d)):
                out[d + k] = out[d - off + k]
            d += count
    return bytes(out[:size])


def lz_unpack(data: bytes, min_count: int = 2, bpp: int = 1) -> bytes:
    """Bloque LZ completo: u32 tamaño comprimido · u32 tamaño original · datos."""
    packed, size = struct.unpack_from('<II', data, 0)
    return lz_unpack_raw(data[8:packed], size, min_count, bpp)


def lz_pack(data: bytes, bpp: int = 1) -> bytes:
    """Bloque LZ con solo literales (banderas 0xFF): válido para el motor, sin comprimir."""
    unit = 8 * bpp
    out = bytearray()
    for i in range(0, len(data), unit):
        chunk = data[i:i + unit]
        units = -(-len(chunk) // bpp)
        out.append((1 << units) - 1 if units < 8 else 0xFF)
        out += chunk
    return struct.pack('<II', len(out) + 8, len(data)) + bytes(out)


